#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${1:-"$ROOT_DIR/.env.deepseek"}"

read -r -p "DeepSeek base URL [https://key.bigsong.site/v1]: " base_url
base_url="${base_url:-https://key.bigsong.site/v1}"

read -r -p "DeepSeek model [deepseek-v4-pro]: " model
model="${model:-deepseek-v4-pro}"

printf "DeepSeek API key: " >&2
stty -echo
IFS= read -r api_key
stty echo
printf "\n" >&2

if [[ -z "$api_key" ]]; then
  echo "DEEPSEEK_API_KEY is empty; aborting." >&2
  exit 1
fi

umask 077
{
  echo "# Local only. This file is ignored by git via .env.*."
  echo "# Generated by scripts/configure_deepseek_env.sh"
  echo
  printf 'DEEPSEEK_API_KEY=%s\n' "$api_key"
  printf 'DEEPSEEK_BASE_URL=%s\n' "$base_url"
  printf 'DEEPSEEK_MODEL=%s\n' "$model"
} > "$ENV_FILE"

chmod 600 "$ENV_FILE"
echo "Wrote DeepSeek environment to $ENV_FILE"
